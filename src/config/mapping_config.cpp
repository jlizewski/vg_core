MappingConfig::MappingConfig() {
  TsdfConfig& tsdf = build.builder.tsdf;
  tsdf.max_depth = 3.5;
  tsdf.edge_ratio = 0.05;
  tsdf.max_incidence_deg = 75.0;
  tsdf.quality_weights = true;
  tsdf.carve = true;
  tsdf.pixel_stride = 2;
  tsdf.threads = 0;
  build.builder.drop_non_keyframes = true;
  pipeline = {"voxels", "surface", "ground", "sun"};
}

io::BuildOptions MappingConfig::build_options() const {
  io::BuildOptions options = build;
  options.cell_size = resolution;
  options.builder.tsdf.voxel_size = voxel_size.value_or(resolution / 2.0);
  options.builder.tsdf.truncation_distance =
      truncation.value_or(3.0 * options.builder.tsdf.voxel_size);
  options.to = to.value_or(std::numeric_limits<double>::infinity());
  return options;
}

SurfaceOptions MappingConfig::surface_options() const { return {cell_size}; }

GroundOptions MappingConfig::ground_options() const { return {ground, cell_size}; }

SunOptions MappingConfig::sun_options() const {
  SunOptions options = sun;
  if (year) {
    options.year = *year;
  } else {
    const auto now = std::chrono::duration_cast<std::chrono::seconds>(
                         std::chrono::system_clock::now().time_since_epoch())
                         .count();
    options.year = utc_year(static_cast<double>(now));
  }
  return options;
}

LayersOptions MappingConfig::layers_options() const {
  LayersOptions options = layers;
  options.cell_size = cell_size;
  return options;
}

