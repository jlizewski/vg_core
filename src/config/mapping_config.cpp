bool is_build_setting(const std::string& path) {
  return path.rfind("map.", 0) == 0 || path.rfind("build.", 0) == 0;
}

void check_stages(const std::vector<std::string>& stages) {
  for (const std::string& stage : stages) {
    if (std::find(kStages.begin(), kStages.end(), stage) == kStages.end()) {
      std::string known;
      for (const std::string& s : kStages) {
        known += (known.empty() ? "" : ", ") + s;
      }
      throw ConfigError("unknown stage " + stage + " (stages: " + known + ")");
    }
  }
}

bool run_stages(MapPackage& package, const MappingConfig& config,
                const std::vector<std::string>& stages) {
  check_stages(stages);
  if (config.build.min_weight) {
    package.set_min_weight(*config.build.min_weight);
  }
  package.set_min_blob_volume(config.min_blob_volume);
  bool all_ran = true;
  for (const std::string& stage : stages) {
    if (stage == "voxels") {
      package.make_voxels();
    } else if (stage == "surface") {
      package.make_surface(config.surface_options());
    } else if (stage == "ground") {
      package.make_ground(config.ground_options());
    } else if (stage == "sun") {
      all_ran = package.make_sun(config.sun_options()) && all_ran;
    } else if (stage == "layers") {
      package.make_layers(config.layers_options());
    }
  }
  return all_ran;
}

void save_settings(const ParamSet& params, const std::filesystem::path& file,
                   const std::string& header) {
  std::ofstream out(file, std::ios::binary);
  params.write_yaml(out, header);
  if (!out) {
    throw ConfigError("cannot write " + file.string());
  }
}

